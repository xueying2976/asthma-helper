const units: Record<Lang, Record<MedUnit, [string, string]>> = {
  en: { puff: ["puff", "puffs"], tablet: ["tablet", "tablets"], capsule: ["capsule", "capsules"], item: ["item", "items"] },
  zh: { puff: ["喷", "喷"], tablet: ["片", "片"], capsule: ["粒", "粒"], item: ["个", "个"] },
};
export function unitLabel(unit: MedUnit | undefined, n: number, lang: Lang) {
  const [one, many] = units[lang][unit ?? "item"];
  return n === 1 ? one : many;
}
export const medUnits: MedUnit[] = ["puff", "tablet", "capsule", "item"];

export function pad2(n: number) {
  return String(n).padStart(2, "0");
}
/** "Oct 16 · 08:40" / "10 月 16 日 · 08:40" from an ISO string, in local time. */
export function fmtLocal(iso: string, lang: Lang) {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  const months = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
  const day = lang === "zh" ? `${d.getMonth() + 1} 月 ${d.getDate()} 日` : `${months[d.getMonth()]} ${d.getDate()}`;
  return `${day} · ${pad2(d.getHours())}:${pad2(d.getMinutes())}`;
}
